"""Build src/support/StatusNames.c: the names of NTSTATUS values for the
Debug build's trace output, from the Windows SDK's shared\\ntstatus.h.

usage: make-status-names.py [ntstatus.h] [--out src/support/StatusNames.c]

Without a path, the newest Windows Kits 10 include directory that holds
shared\\ntstatus.h is used. Every STATUS_ value defined there is listed once,
by value, under the name defined first; the table is sorted, and a lookup
is a binary search.
"""
import os, re, sys

def option(name, default=None):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else default

def newest_header():
    root = os.path.join(os.environ.get('ProgramFiles(x86)', r'C:\Program Files (x86)'), 'Windows Kits', '10', 'Include')
    found = []
    for version in os.listdir(root):
        path = os.path.join(root, version, 'shared', 'ntstatus.h')
        if re.fullmatch(r'\d+(\.\d+){3}', version) and os.path.exists(path):
            found.append((tuple(int(x) for x in version.split('.')), path))
    if not found:
        raise SystemExit('no Windows Kits ntstatus.h found')
    return max(found)[1]

args = [a for a in sys.argv[1:] if not a.startswith('--') and a != option('--out')]
header = args[0] if args else newest_header()
out = option('--out', os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'support', 'StatusNames.c'))
names = {}
for line in open(header, encoding='latin-1'):
    m = re.match(r'#define\s+(STATUS_\w+)\s+\(\(NTSTATUS\)0x([0-9A-Fa-f]{8})L\)', line)
    if m:
        names.setdefault(int(m.group(2), 16), m.group(1))
if names.get(0) is not None:
    names[0] = 'STATUS_SUCCESS'
rows = ['    { (NTSTATUS)0x%08xL, "%s" },' % (value, name) for value, name in sorted(names.items())]
text = '''/**
 * StatusNames.c - the names of NTSTATUS values, for the Debug build's traces.
 *
 * Copyright (c) 2026 Marek Wesolowski (WESMAR)
 * SPDX-License-Identifier: MIT
 *
 * Generated by tools/status/make-status-names.py from the Windows SDK's
 * shared\\ntstatus.h. Do not edit: regenerate.
 */

#include "ext4fs.h"

#if EXT2_DEBUG

typedef struct _EXT2_STATUS_NAME {
    NTSTATUS    Status;
    PCSTR       Name;
} EXT2_STATUS_NAME;

/* by value, as an unsigned number */
static const EXT2_STATUS_NAME Ext2StatusNames[%d] = {
%s
};

PCSTR
Ext2NtStatusToString(IN NTSTATUS Status)
{
    ULONG First = 0, Last = ARRAYSIZE(Ext2StatusNames);

    while (First < Last) {
        ULONG Middle = (First + Last) / 2;

        if ((ULONG)Ext2StatusNames[Middle].Status < (ULONG)Status) {
            First = Middle + 1;
        } else {
            Last = Middle;
        }
    }
    if (First < ARRAYSIZE(Ext2StatusNames) && Ext2StatusNames[First].Status == Status) {
        return Ext2StatusNames[First].Name;
    }
    return "STATUS_UNKNOWN";
}

#endif /* EXT2_DEBUG */
''' % (len(rows), '\n'.join(rows))
with open(out, 'w', encoding='utf-8', newline='\r\n') as f:
    f.write(text)
print('%d names from %s' % (len(rows), header))
