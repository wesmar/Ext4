"""Where every code line of the project comes from, drawn: assets/lineage/*.svg.

usage: lineage-svg.py <repo> <Ext3Fsd> <Ext4Fsd> <linux> [--out assets/lineage]

The C files git tracks - the driver (src), ext4ctl (tools/ext4ctl) and the
test models (tests) - are measured as lineage.py measures them: a token is
inherited when it lies in a run of twelve tokens that also occurs in an
origin (Ext3Fsd, then Ext4Fsd, then Linux). A code line belongs to the
origin of most of its tokens; comments and blank lines count nowhere. The
generated tables of the driver are counted apart. PowerShell, bash and
Python have no counterpart in the origins and count as written here.

Three drawings, each light and dark: summary.svg (the whole project as one
bar), files.svg (every file, sized by its code lines, split by origin) and
subsystems.svg (the driver by directory). Plain SVG: no script, no web font.
"""
import bisect, os, re, subprocess, sys
from collections import Counter
from xml.sax.saxutils import escape

sys.dont_write_bytecode = True     # no __pycache__ left in the repository
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from lineage import COMMENT, GENERATED, ORIGINS, TOKEN, runs, sources, tokens   # noqa: E402

KINDS = ('own', 'gen', 'x3', 'x4', 'lx')
LABEL = {'own': 'Written in this project', 'gen': 'Generated by its own tools',
         'x3': 'Matches Ext3Fsd (Ext2Fsd)', 'x4': 'Matches Ext4Fsd', 'lx': 'Matches Linux'}
OWNER = {'new': 'own', 'Ext3Fsd': 'x3', 'Ext4Fsd': 'x4', 'Linux': 'lx'}
GROUPS = (('driver', 'ext4.sys driver'), ('tests', 'Tests'), ('ext4ctl', 'ext4ctl.exe'), ('tools', 'Generators and build'))
AREA_NOTE = {
    'fsd': 'I/O request handlers: create, read, write, query, rename, delete',
    'ext4': 'on-disk structures: extents, directories, inodes, allocation',
    'include': 'headers and the Linux compatibility types',
    'volume': 'mount, LUKS, LVM, drive letters, protection',
    'journal': 'jbd2 journal: commit, checkpoint, replay',
    'core': 'caches of names, inodes and files; reapers',
    'support': 'name conversion, disk I/O, helpers',
    'driver': 'load, unload, dispatch',
    'nls': 'code page converters',
    'linux': 'buffer heads and the red-black tree',
    'unicode': 'case folding',
    'crypto': 'AES-XTS for LUKS',
    'tables': 'code page and case-folding tables, NTSTATUS names',
}
THEMES = {
    'light': {'paper': '#ffffff', 'ink': '#1a1f1c', 'muted': '#59625d', 'rule': '#d8ddd6', 'own': '#1d7f47',
              'soft': '#cfe8d8', 'x3': '#c08417', 'x4': '#b1502a', 'lx': '#3a6aa3', 'on': '#ffffff'},
    'dark': {'paper': '#0d1117', 'ink': '#e5eae6', 'muted': '#9aa49f', 'rule': '#2b332e', 'own': '#43b874',
             'soft': '#1d3a29', 'x3': '#dba541', 'x4': '#de7a50', 'lx': '#6f9fd6', 'on': '#0c100e'},
}
SANS = "'Segoe UI', 'Helvetica Neue', Arial, sans-serif"
MONO = "Consolas, 'Cascadia Mono', Menlo, 'DejaVu Sans Mono', monospace"
K = 12

# ---------------------------------------------------------------- measuring

def code_lines(path, known):
    """Code lines of one C file by owner, as lineage.py owns its tokens."""
    with open(path, encoding='latin-1') as f:
        text = f.read().replace('\\\n', ' \n')
    text = COMMENT.sub(lambda m: re.sub(r'[^\n]', ' ', m.group(0)), text)
    starts = [0] + [m.end() for m in re.finditer('\n', text)]
    found, line = [], []
    for m in TOKEN.finditer(text):
        found.append(m.group(0))
        line.append(bisect.bisect_right(starts, m.start()))
    owner = [None] * len(found)
    for name, shared in known:
        for i in range(len(found) - K + 1):
            if hash(tuple(found[i:i + K])) in shared:
                for j in range(i, i + K):
                    owner[j] = owner[j] or name
    per_line = {}
    for o, ln in zip(owner, line):
        per_line.setdefault(ln, Counter())[o or 'new'] += 1
    result = Counter()
    for c in per_line.values():
        best = max(c.values())
        result[OWNER[next(o for o in ORIGINS + ('new',) if c.get(o) == best)]] += 1   # ties to the origin
    return result

def script_lines(path, powershell):
    """Non-blank lines that are not comments (# lines; <# #> blocks in PowerShell)."""
    n, block = 0, False
    for line in open(path, encoding='utf-8', errors='replace'):
        t = line.strip()
        if powershell and t.startswith('<#'):
            block = True
        if block:
            block = not t.endswith('#>')
            continue
        if t and not t.startswith('#'):
            n += 1
    return n

def measure(repo, origins):
    known = []
    for name, root in zip(ORIGINS, origins):
        shared = set()
        for _, path in sources(root):
            shared |= runs(tokens(path, False), K)
        known.append((name, shared))
    tracked = subprocess.run(['git', '-C', repo, '-c', 'core.quotepath=false', 'ls-files'],
                             capture_output=True, text=True, check=True).stdout.split('\n')
    files = []
    for rel in filter(None, tracked):
        path = os.path.join(repo, rel)
        if rel.endswith(('.c', '.h')):
            if rel.startswith('src/'):
                inner = rel[4:]
                if any(re.search(g, inner) for g in GENERATED):
                    files.append(('driver', 'tables', rel, Counter(gen=code_lines(path, [])['own'])))
                else:
                    files.append(('driver', inner.split('/')[0], rel, code_lines(path, known)))
            elif rel.startswith('tools/ext4ctl/'):
                files.append(('ext4ctl', 'ext4ctl', rel, code_lines(path, known)))
            elif rel.startswith('tests/'):
                files.append(('tests', 'models', rel, code_lines(path, known)))
        elif rel.endswith(('.ps1', '.sh', '.py')):
            group, area = ('tests', 'runners') if rel.startswith('tests/') else ('tools', 'generators')
            files.append((group, area, rel, Counter(own=script_lines(path, rel.endswith('.ps1')))))
    return [f for f in files if sum(f[3].values())]

# ---------------------------------------------------------------- drawing

def fmt(n):
    return '{:,}'.format(int(round(n))).replace(',', ' ')

def pct(a, b, digits=1):
    return '%.*f' % (digits, 100.0 * a / b)

def total(c):
    return sum(c[k] for k in KINDS)

def style(t, scope):
    """Rules under the drawing's own id: an SVG pasted into a page styles the whole page otherwise."""
    rules = (('text', 'font-family:%s;fill:%s' % (SANS, t['ink'])), ('.l-mono', 'font-family:%s' % MONO),
             ('.l-muted', 'fill:%s' % t['muted']), ('.l-own', 'fill:%s' % t['own']),
             ('.l-gen', 'fill:url(#%s-hatch)' % scope), ('.l-x3', 'fill:%s' % t['x3']),
             ('.l-x4', 'fill:%s' % t['x4']), ('.l-lx', 'fill:%s' % t['lx']), ('.l-on', 'fill:%s' % t['on']))
    return '<style>' + ''.join('#%s %s{%s}' % (scope, s, r) for s, r in rules) + '</style>'

def pattern(t, scope):
    return ('<defs><pattern id="%s-hatch" width="6" height="6" patternUnits="userSpaceOnUse" patternTransform="rotate(45)">'
            '<rect width="6" height="6" fill="%s"/><rect width="3" height="6" fill="%s"/></pattern></defs>'
            % (scope, t['soft'], t['own']))

def svg(width, height, title, t, scope, body):
    return ('<svg xmlns="http://www.w3.org/2000/svg" id="%s" viewBox="0 0 %d %d" width="%d" height="%d" '
            'style="max-width:100%%;height:auto" role="img" aria-label="%s">%s%s<rect width="%d" height="%d" fill="%s"/>%s</svg>\n'
            % (scope, width, height, width, height, escape(title, {'"': '&quot;'}), style(t, scope), pattern(t, scope),
               width, height, t['paper'], ''.join(body)))

def text(x, y, s, size, cls='', anchor='start', weight=400):
    cls = ' '.join('l-' + c for c in cls.split())
    c = ' class="%s"' % cls if cls else ''
    a = ' text-anchor="%s"' % anchor if anchor != 'start' else ''
    w = ' font-weight="%d"' % weight if weight != 400 else ''
    return '<text x="%.1f" y="%.1f" font-size="%g"%s%s%s>%s</text>' % (x, y, size, c, a, w, escape(s))

def fits(s, width, size):
    """s cut to what a monospace face of this size shows in width, or ''."""
    room = int(width / (size * 0.6))
    if room < 3:
        return ''
    return s if len(s) <= room else s[:room - 1] + '…'

def split(x, y, w, h, c):
    """Rectangles of the kinds of c, along the longer side."""
    n, at, out = total(c), 0.0, []
    for k in KINDS:
        if not c[k]:
            continue
        part = (w if w >= h else h) * c[k] / n
        if w >= h:
            out.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" class="l-%s"/>' % (x + at, y, part, h, k))
        else:
            out.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" class="l-%s"/>' % (x, y + at, w, part, k))
        at += part
    return out

def summary(files, t, scope):
    all_ = Counter()
    for f in files:
        all_.update(f[3])
    n, width = total(all_), 1000
    own = all_['own'] + all_['gen']
    body = [text(0, 92, pct(own, n, 0) + ' %', 104, 'own', weight=800),
            text(250, 44, "of the project's %s code lines are written or generated here" % fmt(n), 20, weight=600),
            text(250, 72, '%s %% written by hand · %s %% generated by its own tools · %s %% inherited'
                 % (pct(all_['own'], n), pct(all_['gen'], n), pct(n - own, n)), 15, 'muted'),
            text(250, 96, 'driver, ext4ctl.exe, tests and generators; comments and blank lines left out', 13, 'muted')]
    x = 0.0
    for k in KINDS:
        if all_[k]:
            w = width * all_[k] / n
            body.append('<rect x="%.1f" y="122" width="%.1f" height="38" class="l-%s"><title>%s: %s lines</title></rect>'
                        % (x, w, k, LABEL[k], fmt(all_[k])))
            x += w
    for i, k in enumerate(KINDS):
        kx = i * 200
        body += ['<rect x="%d" y="180" width="13" height="13" rx="2" class="l-%s"/>' % (kx, k),
                 text(kx + 20, 192, LABEL[k], 13.5, weight=600),
                 text(kx + 20, 212, '%s lines · %s %%' % (fmt(all_[k]), pct(all_[k], n)), 12.5, 'mono muted')]
    title = ("%s %% of the project's %s code lines are written or generated in this project" % (pct(own, n, 0), fmt(n)))
    return svg(width, 226, title, t, scope, body), all_

def squarify(items, x, y, w, h):
    """Bruls, Huizing and van Wijk: rows of rectangles kept near square. items: (value, payload), largest first."""
    out, items = [], [i for i in items if i[0] > 0]
    scale = w * h / sum(v for v, _ in items) if items else 0
    def worst(row, side):
        s = sum(row)
        return max(max(side * side * r / (s * s), s * s / (side * side * r)) for r in row)
    i = 0
    while i < len(items):
        side, row, j = min(w, h), [items[i][0] * scale], i + 1
        while j < len(items) and worst(row + [items[j][0] * scale], side) <= worst(row, side):
            row.append(items[j][0] * scale)
            j += 1
        s = sum(row)
        if w >= h:
            cw, yy = s / h, y
            for a, k in zip(row, range(i, j)):
                out.append((x, yy, cw, a / cw, items[k][1]))
                yy += a / cw
            x, w = x + cw, w - cw
        else:
            rh, xx = s / w, x
            for a, k in zip(row, range(i, j)):
                out.append((xx, y, a / rh, rh, items[k][1]))
                xx += a / rh
            y, h = y + rh, h - rh
        i = j
    return out

def file_map(files, t, scope):
    width, height = 1000, 660
    groups = []
    for g, name in GROUPS:
        areas = {}
        for f in files:
            if f[0] == g:
                areas.setdefault(f[1], []).append(f)
        if areas:
            groups.append((sum(total(f[3]) for a in areas.values() for f in a), (g, name, areas)))
    groups.sort(key=lambda v: -v[0])
    body = []
    for gx, gy, gw, gh, (g, name, areas) in squarify(groups, 0, 0, width, height):
        gx, gy, gw, gh = gx + 3, gy + 3, gw - 6, gh - 6
        body.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="none" stroke="%s"/>' % (gx, gy, gw, gh, t['rule']))
        size = sum(total(f[3]) for a in areas.values() for f in a)
        body.append(text(gx + 6, gy + 15, fits('%s · %s lines' % (name, fmt(size)), gw - 12, 12.5), 12.5, weight=700))
        items = sorted(((sum(total(f[3]) for f in fl), (a, fl)) for a, fl in areas.items()), key=lambda v: -v[0])
        for ax, ay, aw, ah, (a, fl) in squarify(items, gx + 2, gy + 21, gw - 4, gh - 23):
            head = 13 if len(areas) > 1 and aw > 60 and ah > 46 else 0
            if head:
                body.append(text(ax + 2, ay + 10, fits('%s %s' % (a, fmt(sum(total(f[3]) for f in fl))), aw - 4, 10), 10, 'mono muted'))
            leaves = sorted(((total(f[3]), f) for f in fl), key=lambda v: -v[0])
            for x, y, w, h, f in squarify(leaves, ax + 1, ay + head + 1, aw - 2, ah - head - 2):
                x, y, w, h = x + 0.5, y + 0.5, max(w - 1, 0.5), max(h - 1, 0.5)
                c, n = f[3], total(f[3])
                tip = '%s — %s lines: ' % (f[2], fmt(n)) + ', '.join(
                    '%s %s %%' % (LABEL[k].lower(), pct(c[k], n, 0)) for k in KINDS if c[k])
                body.append('<g><title>%s</title>' % escape(tip) + ''.join(split(x, y, w, h, c)))
                label = fits(f[2].split('/')[-1], w - 8, 10) if h > 22 else ''
                if label:
                    body.append(text(x + 4, y + 13, label, 10, 'mono on' if not c['gen'] else 'mono'))
                body.append('</g>')
    return svg(width, height, 'Every code file of the project, sized by its code lines and split by origin', t, scope, body)

def subsystems(files, t, scope):
    by = {}
    for f in files:
        if f[0] == 'driver':
            by.setdefault(f[1], Counter()).update(f[3])
    rows = sorted(by.items(), key=lambda kv: -total(kv[1]))
    width, row_h, left, right = 1000, 40, 92, 96
    biggest = total(rows[0][1])
    body = []
    for i, (a, c) in enumerate(rows):
        y, n = 6 + i * row_h, total(c)
        body.append(text(0, y + 13, a, 13, 'mono', weight=600))
        x, span = left, (width - left - right) * n / biggest
        for k in KINDS:
            if c[k]:
                w = span * c[k] / n
                body.append('<rect x="%.1f" y="%d" width="%.1f" height="16" class="l-%s"/>' % (x, y, w, k))
                x += w
        body.append(text(left, y + 31, AREA_NOTE.get(a, ''), 11.5, 'muted'))
        body.append(text(width, y + 13, 'generated' if a == 'tables' else pct(c['own'], n, 0) + ' %', 13, 'mono', 'end', 600))
        body.append(text(width, y + 29, fmt(n), 11, 'mono muted', 'end'))
    return svg(width, 6 + len(rows) * row_h, 'The driver by subsystem: code lines and new share', t, scope, body)

def main():
    repo, origins = sys.argv[1], sys.argv[2:5]
    out = sys.argv[sys.argv.index('--out') + 1] if '--out' in sys.argv else os.path.join(repo, 'assets', 'lineage')
    os.makedirs(out, exist_ok=True)
    files = measure(repo, origins)
    for theme, t in THEMES.items():
        suffix = '' if theme == 'light' else '-dark'
        drawn, all_ = summary(files, t, 'ext4-lineage-summary' + suffix)
        for name, content in (('summary', drawn), ('files', file_map(files, t, 'ext4-lineage-files' + suffix)),
                              ('subsystems', subsystems(files, t, 'ext4-lineage-subsystems' + suffix))):
            with open(os.path.join(out, name + suffix + '.svg'), 'w', encoding='utf-8', newline='\n') as f:
                f.write(content)
    n, plain = total(all_), lambda v: fmt(v).replace(' ', ' ')     # any console's code page
    print('%d files, %s code lines: ' % (len(files), plain(n)) + ', '.join(
        '%s %s (%s %%)' % (k, plain(all_[k]), pct(all_[k], n)) for k in KINDS))
    for g, name in GROUPS:
        c = Counter()
        for f in files:
            if f[0] == g:
                c.update(f[3])
        print('  %-22s %7s lines, %s %% written here' % (name, plain(total(c)), pct(c['own'], total(c))))

if __name__ == '__main__':
    main()
